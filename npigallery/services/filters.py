@dataclass(frozen=True)
class FilterChoice:
    name: str = ORIGINAL
    intensity: int = INTENSITY_MAX

    def is_identity(self) -> bool:
        return self.name == ORIGINAL or self.intensity <= 0 or self.name not in _RECIPES


@lru_cache(maxsize=32)
def _tables(name: str) -> tuple[tuple[float, ...], list[int]]:
    matrix, curves = _RECIPES[name]
    rows = [matrix[0:3] + (0.0,), matrix[3:6] + (0.0,), matrix[6:9] + (0.0,)]
    lut: list[int] = []
    last = KNOTS - 1
    for knots in curves:
        for i in range(256):
            position = i / 255 * last
            low = min(int(position), last - 1)
            fraction = position - low
            value = knots[low] + (knots[low + 1] - knots[low]) * fraction
            lut.append(min(255, max(0, round(value * 255))))
    return tuple(value for row in rows for value in row), lut


def apply_filter(image: Image.Image, choice: FilterChoice) -> Image.Image:
    if choice.is_identity():
        return image
    matrix, lut = _tables(choice.name)
    alpha = image.getchannel("A") if "A" in image.getbands() else None
    rgb = image.convert("RGB")
    result = rgb.convert("RGB", matrix).point(lut)
    if choice.intensity < INTENSITY_MAX:
        result = Image.blend(rgb, result, choice.intensity / INTENSITY_MAX)
    if alpha is not None:
        result.putalpha(alpha)
    return result
